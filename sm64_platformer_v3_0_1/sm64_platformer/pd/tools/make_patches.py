s.obj("r_note", "r synth_note", 20, 40)
s.obj("poly", "poly 6 1", 20, 80)
s.obj("pack", "pack f f f", 20, 120)
s.obj("voices", "clone -s 1 analog_voice 6", 20, 160)
s.obj("vol", "*~ 0.8", 20, 200)
s.obj("r_vol", "r synth_volume", 150, 170)
s.obj("dac", "throw~ analog_out", 20, 240)   # to the mixer in instruments.pd
s.obj("r_off", "r synth_all_off", 220, 40)
s.msg("stop", "stop", 220, 80)
s.con("r_note", 0, "poly", 0)
s.con("poly", 0, "pack", 0)
s.con("poly", 1, "pack", 1)
s.con("poly", 2, "pack", 2)

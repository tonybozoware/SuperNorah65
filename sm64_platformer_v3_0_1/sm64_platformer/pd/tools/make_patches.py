s.con("vol", 0, "dac", 0)
s.con("r_off", 0, "stop", 0)
s.con("stop", 0, "poly", 0)
s.obj("lb", "loadbang", 420, 40)
defaults = """; synth_osc1_level 1; synth_osc2_level 0.8; synth_sub_level 0.4; synth_detune 7;
 synth_cutoff 700; synth_resonance 0.35; synth_filter_env_amount 2500; synth_filter_velocity 0.5;
 synth_filter_attack 5; synth_filter_decay 350; synth_filter_sustain 0.25; synth_filter_release 300;
 synth_attack 5; synth_decay 300; synth_sustain 0.7; synth_release 300; synth_volume 0.8;
 synth_pulse_width 0.5; synth_pulse_mix 0; synth_drive 0;
 synth_plaits_level 0; synth_plaits_model 8; synth_plaits_harmonics 0.5; synth_plaits_timbre 0.5;
 synth_plaits_morph 0.5; synth_plaits_decay 0.5; synth_plaits_colour 0.5; synth_plaits_triggered 0"""

# Generates the Biryani64 Pure Data patches: analog_synth.pd (+ analog_voice.pd)
# and drums.pd. Every sound parameter is a Pd "receive" name that Godot can set
# with send_float(name, value).
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))   # pdgen.py sits next to this file
from pdgen import Patch
out = sys.argv[1]

# ---------------------------------------------------------------- voice
v = Patch()
v.comment("one voice of analog_synth: 2 saw/pulse oscs + sub square + Plaits > drive > Moog ladder filter > amp", 20, 2)
v.obj("in", "inlet", 20, 30)
v.obj("unpack", "unpack f f", 20, 60)
# --- pitch
v.obj("mtof", "mtof", 20, 100)
v.obj("tf", "t f f f", 20, 130)
v.obj("osc1", "phasor~", 20, 200)
v.obj("det_mul", "* 1", 110, 170)
v.obj("osc2", "phasor~", 110, 200)
v.obj("sub_mul", "* 0.5", 200, 170)
v.obj("sub", "phasor~", 200, 200)
v.obj("r_detune", "r synth_detune", 300, 100)
v.obj("det_expr", "expr pow(2, $f1/1200)", 300, 130)
v.con("in", 0, "unpack", 0)
v.con("unpack", 0, "mtof", 0)
v.con("mtof", 0, "tf", 0)
v.con("tf", 2, "osc1", 0)
v.con("tf", 1, "det_mul", 0)
v.con("tf", 0, "sub_mul", 0)
v.con("det_mul", 0, "osc2", 0)
v.con("sub_mul", 0, "sub", 0)
v.con("r_detune", 0, "det_expr", 0)
v.con("det_expr", 0, "det_mul", 1)
# osc 1 and 2: saw (phasor*2-1) crossfaded with a pulse of width $f2 (DC removed),
# pulse mix $f3: 0 = all saw, 1 = all pulse. sub = (phasor>0.5)*2-1
v.obj("saw1", "expr~ ($v1*2-1)*(1-$f3) + 2*(($v1<$f2)-$f2)*$f3", 20, 240)
v.obj("saw2", "expr~ ($v1*2-1)*(1-$f3) + 2*(($v1<$f2)-$f2)*$f3", 110, 240)
v.obj("sq", "expr~ ($v1>0.5)*2-1", 200, 240)
v.con("osc1", 0, "saw1", 0)
v.con("osc2", 0, "saw2", 0)
v.con("sub", 0, "sq", 0)
v.obj("r_pw", "r synth_pulse_width", 300, 200)
v.obj("pw_clip", "clip 0.02 0.98", 300, 225)
v.obj("r_pmix", "r synth_pulse_mix", 420, 200)
v.con("r_pw", 0, "pw_clip", 0)
v.con("pw_clip", 0, "saw1", 1)
v.con("pw_clip", 0, "saw2", 1)
v.con("r_pmix", 0, "saw1", 2)
v.con("r_pmix", 0, "saw2", 2)
v.obj("lvl1", "*~ 1", 20, 280)
v.obj("lvl2", "*~ 1", 110, 280)
v.obj("lvl3", "*~ 0", 200, 280)
v.obj("r_l1", "r synth_osc1_level", 20, 320)
v.obj("r_l2", "r synth_osc2_level", 170, 320)
v.obj("r_l3", "r synth_sub_level", 330, 320)
v.con("saw1", 0, "lvl1", 0)
v.con("saw2", 0, "lvl2", 0)
v.con("sq", 0, "lvl3", 0)
v.con("r_l1", 0, "lvl1", 1)
v.con("r_l2", 0, "lvl2", 1)
v.con("r_l3", 0, "lvl3", 1)
# Plaits macro-oscillator ([plaits~], built into godot-pd), free-running by
# default so it goes through this voice's drive, filter and envelopes like the saws.
v.msg("pl_note", "note $1", 560, 20)
v.obj("plaits", "plaits~", 560, 300)
v.obj("pl_lvl", "*~ 0", 560, 330)
v.obj("r_pll", "r synth_plaits_level", 700, 230)
v.obj("pl_gain", "* 3", 700, 260)          # Plaits is quieter than the saws
v.obj("pl_on", "> 0", 820, 260)
v.msg("pl_active", "active $1", 820, 290)
v.obj("r_plm", "r synth_plaits_model", 900, 20)
v.msg("pl_model", "model $1", 900, 50)
v.obj("r_plh", "r synth_plaits_harmonics", 900, 80)
v.msg("pl_harm", "harmonics $1", 900, 110)
v.obj("r_plt", "r synth_plaits_timbre", 900, 140)
v.msg("pl_timb", "timbre $1", 900, 170)
v.obj("r_plmo", "r synth_plaits_morph", 1080, 20)
v.msg("pl_morph", "morph $1", 1080, 50)
v.obj("r_pld", "r synth_plaits_decay", 1080, 80)
v.msg("pl_decay", "decay $1", 1080, 110)
v.obj("r_plc", "r synth_plaits_colour", 1080, 140)
v.msg("pl_colour", "colour $1", 1080, 170)
v.obj("r_pltr", "r synth_plaits_triggered", 1080, 200)
v.msg("pl_trig_mode", "triggered $1", 1080, 230)
v.obj("pl_trig_b", "t b", 560, 90)
v.msg("pl_trig", "trig", 560, 120)
v.con("unpack", 0, "pl_note", 0)
v.con("pl_note", 0, "plaits", 0)
for r, m in [("r_plm","pl_model"),("r_plh","pl_harm"),("r_plt","pl_timb"),("r_plmo","pl_morph"),
             ("r_pld","pl_decay"),("r_plc","pl_colour"),("r_pltr","pl_trig_mode")]:
    v.con(r, 0, m, 0)
    v.con(m, 0, "plaits", 0)
v.con("r_pll", 0, "pl_gain", 0)
v.con("pl_gain", 0, "pl_lvl", 1)
v.con("r_pll", 0, "pl_on", 0)
v.con("pl_on", 0, "pl_active", 0)
v.con("pl_active", 0, "plaits", 0)
v.con("plaits", 0, "pl_lvl", 0)
v.con("pl_trig_b", 0, "pl_trig", 0)
v.con("pl_trig", 0, "plaits", 0)
v.obj("mixgain", "*~ 0.35", 20, 360)
v.con("lvl1", 0, "mixgain", 0)
v.con("lvl2", 0, "mixgain", 0)
v.con("lvl3", 0, "mixgain", 0)
v.con("pl_lvl", 0, "mixgain", 0)
# --- envelopes (vline~ ADSR). velocity fires before note (unpack is right-to-left)
v.obj("vel_sel", "moses 1", 450, 60)
v.obj("vel_norm", "/ 127", 520, 90)
v.obj("vel_t", "t f f f", 520, 120)
#  amp env
v.obj("a_sus", "* 0.7", 600, 150)
v.obj("a_pack", "pack f f f f", 520, 180)
v.msg("a_msg", "$1 $2, $3 $4 $2", 520, 210)
v.obj("a_env", "vline~", 520, 240)
v.obj("r_att", "r synth_attack", 700, 120)
v.obj("r_dec", "r synth_decay", 700, 150)
v.obj("r_sus", "r synth_sustain", 700, 180)
v.con("unpack", 1, "vel_sel", 0)
v.con("vel_sel", 1, "vel_norm", 0)
v.con("vel_sel", 1, "pl_trig_b", 0)
v.con("vel_norm", 0, "vel_t", 0)
v.con("vel_t", 2, "a_sus", 0)
v.con("a_sus", 0, "a_pack", 2)
v.con("vel_t", 0, "a_pack", 0)
v.con("r_att", 0, "a_pack", 1)
v.con("r_dec", 0, "a_pack", 3)
v.con("r_sus", 0, "a_sus", 1)
v.con("a_pack", 0, "a_msg", 0)
v.con("a_msg", 0, "a_env", 0)
#  amp release
v.obj("rel_b", "t b", 450, 250)
v.obj("rel_f", "f 300", 450, 280)
v.msg("rel_msg", "0 $1", 450, 310)
v.obj("r_rel", "r synth_release", 560, 280)
v.con("vel_sel", 0, "rel_b", 0)
v.con("rel_b", 0, "rel_f", 0)
v.con("r_rel", 0, "rel_f", 1)
v.con("rel_f", 0, "rel_msg", 0)
v.con("rel_msg", 0, "a_env", 0)
#  filter env (peak 1, scaled by velocity amount)
v.obj("f_vel", "expr 1 - $f2 + $f2*$f1", 760, 240)
v.obj("r_fvel", "r synth_filter_velocity", 900, 210)
v.obj("f_t", "t f f", 760, 270)
v.obj("f_sus", "* 0.3", 840, 300)
v.obj("f_pack", "pack f f f f", 760, 330)
v.msg("f_msg", "$1 $2, $3 $4 $2", 760, 360)
v.obj("f_env", "vline~", 760, 390)
v.obj("r_fatt", "r synth_filter_attack", 940, 270)
v.obj("r_fdec", "r synth_filter_decay", 940, 300)
v.obj("r_fsus", "r synth_filter_sustain", 940, 330)
v.con("vel_t", 1, "f_vel", 0)
v.con("r_fvel", 0, "f_vel", 1)
v.con("f_vel", 0, "f_t", 0)
v.con("f_t", 1, "f_sus", 0)
v.con("f_sus", 0, "f_pack", 2)
v.con("f_t", 0, "f_pack", 0)
v.con("r_fatt", 0, "f_pack", 1)
v.con("r_fdec", 0, "f_pack", 3)
v.con("r_fsus", 0, "f_sus", 1)
v.con("f_pack", 0, "f_msg", 0)
v.con("f_msg", 0, "f_env", 0)
v.obj("frel_f", "f 300", 620, 420)
v.msg("frel_msg", "0 $1", 620, 450)
v.obj("r_frel", "r synth_filter_release", 700, 420)
v.con("rel_b", 0, "frel_f", 0)
v.con("r_frel", 0, "frel_f", 1)
v.con("frel_f", 0, "frel_msg", 0)
v.con("frel_msg", 0, "f_env", 0)
# --- filter: cutoff = base + env * amount (Hz), clipped; resonance 0..1 -> 0..3.8
v.obj("env_amt", "*~ 2000", 760, 430)
v.obj("r_famt", "r synth_filter_env_amount", 860, 460)
v.obj("cut_add", "+~ 800", 760, 470)
v.obj("r_cut", "r synth_cutoff", 860, 500)
v.obj("cut_clip", "clip~ 20 18000", 760, 510)
v.con("f_env", 0, "env_amt", 0)
v.con("r_famt", 0, "env_amt", 1)
v.con("env_amt", 0, "cut_add", 0)
v.con("r_cut", 0, "cut_add", 1)
v.con("cut_add", 0, "cut_clip", 0)
v.obj("r_res", "r synth_resonance", 300, 400)
v.obj("res_scale", "* 3.8", 300, 430)
v.obj("res_sig", "sig~ 1", 300, 460)
v.con("r_res", 0, "res_scale", 0)
v.con("res_scale", 0, "res_sig", 0)
# --- pre-filter drive: tanh(x*g) * c, g = 1 + drive*7, c = 0.6/tanh(0.6g) so a
# typical peak keeps its level and more drive means more grit, not more volume
v.obj("r_drive", "r synth_drive", 300, 480)
v.obj("drv_g", "expr 1 + $f1*7", 300, 505)
v.obj("drv_t", "t f f", 300, 530)
v.obj("drv_c", "expr 0.6/tanh(0.6*$f1)", 420, 555)
v.obj("drive", "expr~ tanh($v1*$f2)*$f3", 20, 490)
v.con("mixgain", 0, "drive", 0)
v.con("r_drive", 0, "drv_g", 0)
v.con("drv_g", 0, "drv_t", 0)
v.con("drv_t", 1, "drv_c", 0)
v.con("drv_c", 0, "drive", 2)
v.con("drv_t", 0, "drive", 1)
v.obj("vcf", "bob~", 20, 520)
v.con("drive", 0, "vcf", 0)
v.con("cut_clip", 0, "vcf", 1)
v.con("res_sig", 0, "vcf", 2)
v.obj("vca", "*~", 20, 560)
v.con("vcf", 0, "vca", 0)
v.con("a_env", 0, "vca", 1)
v.obj("out", "outlet~", 20, 600)
v.con("vca", 0, "out", 0)
v.save(f"{out}/analog_voice.pd")

# ---------------------------------------------------------------- synth
s = Patch()

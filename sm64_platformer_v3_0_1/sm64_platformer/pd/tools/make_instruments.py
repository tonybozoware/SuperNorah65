# Part of make_patches.py (run that one): the Instruments mixer and the new
# instruments - noise, orchestra hit, timpani, sampler and Dexed. Every
# instrument ends in [throw~ <name>_out]; instruments.pd catches them all, sets
# each one's level and delay send, runs the send through two [clouds~] (a tape
# echo, then grains) and plays the mix.
# Expects `Patch` and `out` from make_patches.py.


def env_line(p, name, x, y):
    """vline~ fed a "peak attack decay" list: up in `attack` ms, down in `decay` ms."""
    p.msg(name + "_msg", "$1 $2, 0 $3 $2", x, y)
    p.obj(name, "vline~", x, y + 30)
    p.con(name + "_msg", 0, name, 0)
    return name


